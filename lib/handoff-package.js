function readEnvExample(projectPath) {
  const envPath = path.join(projectPath, '.env.example');
  if (!fs.existsSync(envPath)) return [];
  return fs
    .readFileSync(envPath, 'utf8')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#') && line.includes('='))
    .map((line) => line.split('=')[0].trim())
    .filter(Boolean);
}

function buildSmokeHint(scaffold = {}) {
  switch (scaffold.templateId || scaffold.id) {
    case 'nextjs':
      return 'You will know it worked when `npm run dev` starts cleanly and the homepage loads at `http://localhost:3000`.';
    case 'astro':
      return 'You will know it worked when `npm run dev` starts cleanly and the Astro homepage renders locally.';
    case 'static-html':
    case 'html-alpine':
      return 'You will know it worked when `index.html` opens without missing local assets and the primary user journey is visible.';
    default:
      return 'You will know it worked when the scaffold starts cleanly and the entrypoint renders without missing local assets.';
  }
}

function buildLaunchChecklist({
  projectName,
  scaffold,
  verification = null,
  designReference = 'none',
  createdAt,
  projectPath,
}) {
  const envVars = readEnvExample(projectPath);
  const commands = scaffold?.commands || {};
  const checks = Array.isArray(verification?.checks) ? verification.checks : [];
  const warnings = checks
    .filter((check) => check.status !== 'passed')
    .map(
      (check) => `- ${check.label}: ${check.status}${check.command ? ` (${check.command})` : ''}`
    );
  const skippedChecks = checks
    .filter((check) => check.status === 'skipped' || check.status === 'not_configured')
    .map((check) => `- ${check.label}: ${check.status}`);
  const commandList = Object.keys(commands).length
    ? Object.entries(commands)
        .map(([name, command]) => `- ${name}: \`${command}\``)
        .join('\n')
    : '- Open `index.html` directly in a browser.';
  const envList = envVars.length
    ? envVars.map((name) => `- \`${name}\``).join('\n')
    : '- No `.env.example` file was generated for this scaffold.';
  const warningList = warnings.length ? warnings.join('\n') : '- None.';
  const skippedList = skippedChecks.length ? skippedChecks.join('\n') : '- None.';

  return `# Launch checklist\n\n## Project\n\n- Name: ${projectName}\n- Generated: ${createdAt}\n- Template: ${scaffold?.templateId || scaffold?.id || 'unknown'}\n- Entrypoint: \`${scaffold?.entrypoint || 'unknown'}\`\n- Design reference: \`${designReference || 'none'}\`\n\n## Run commands\n\n${commandList}\n\n## Required environment variables\n\n${envList}\n\n## Verification summary\n\n- Overall: ${verification?.overall || 'Not run'}\n- Passed: ${verification?.summary?.passed || 0}\n- Failed: ${verification?.summary?.failed || 0}\n- Warnings: ${(verification?.summary?.skipped || 0) + (verification?.summary?.not_configured || 0)}\n\n### Skipped or not configured checks\n\n${skippedList}\n\n## Known limitations and warnings\n\n${warningList}\n\n## Human actions still required\n\n- Run the scaffold locally and confirm the core journey works in a browser.\n- Replace demo content, temporary copy, and local placeholders with production-ready implementation details.\n- Add real environment values outside this package if the final build needs external services.\n\n## Success check\n\n${buildSmokeHint(scaffold)}\n\n## Related files\n\n- [Blueprint](./blueprint.md)\n- [Prototype](./prototype.html)\n- [Design reference](./design-system.md)\n- [Manifest](./cauldron.project.json)\n- [Launch checklist](./launch-checklist.md)\n`;
}

async function createHandoffPackage({
  projectPath,
  projectName,
  safeName,
  cauldronVersion,
  blueprint = '',
  prototypeHtml = '',
  designReference = 'none',
  designSystemContent = '',
  templateId = '',
  projectType = 'app',
  sessionId = '',
  workspace = null,
  agentId = 'handoff',
  agentScope = null,
  orchestration = null,
  command = null,
  bootstrap = false,
  verification = null,
  includeDesignPackage = false,
}) {
  fs.mkdirSync(projectPath, { recursive: true });

  const buildFilesList = copyWorkspaceFiles({ workspace, sessionId, projectPath });
  let useBlueprint = blueprint;

  if (sessionId && !useBlueprint) {
    try {
      const files = workspace.wsListFiles(sessionId);
      useBlueprint = `# Build Session: ${safeName}\n\nCopied ${buildFilesList.length} files from build session ${sessionId}.\n\n## Files\n${files.map((f) => `- ${f}`).join('\n')}`;
    } catch {
      useBlueprint = `# Build Session: ${safeName}\n\nBuild handoff from session ${sessionId}.`;
    }
  }

  const files = {};
  if (writeFileIfContent(path.join(projectPath, 'blueprint.md'), useBlueprint || ''))
    files.blueprint = 'blueprint.md';

  const fullPrototype = wrapPrototypeHtml(prototypeHtml) || prototypeFromBlueprint(useBlueprint);
  if (fullPrototype) {
    writeFileIfContent(path.join(projectPath, 'prototype.html'), fullPrototype);
    files.prototype = 'prototype.html';
  }

  const designSystemMarkdown =
    designSystemContent && designSystemContent.trim()
      ? designSystemContent
      : `# Design Reference\n\nSelected design reference: ${designReference || 'none'}\n`;
  writeFileIfContent(path.join(projectPath, 'design-system.md'), designSystemMarkdown);
  files.designSystem = 'design-system.md';

  let designPackage = null;
  if (includeDesignPackage) {
    designPackage = buildDesignPackage({
      designReference,
      designSystemContent: designSystemMarkdown,
      prototypeHtml: fullPrototype,
    });
    writeFileIfContent(path.join(projectPath, 'docs', 'design.md'), designPackage.markdown);
    writeFileIfContent(path.join(projectPath, 'docs', 'design.html'), designPackage.html);
    files.designPackage = {
      markdown: 'docs/design.md',
      html: 'docs/design.html',
    };
  }

  const scope = agentScope || getAgentScope(agentId);

  writeFileIfContent(
    path.join(projectPath, 'README.md'),
    buildReadme({ projectName, agentId, templateId, projectType, agentScope: scope })
  );
  files.readme = 'README.md';

  writeFileIfContent(
    path.join(projectPath, 'agent-prompt.md'),
    buildAgentPrompt({
      projectName,
      templateId,
      projectType,
      agentId,
      agentScope: scope,
      orchestration,
    })
  );
  files.agentPrompt = 'agent-prompt.md';

  writeFileIfContent(path.join(projectPath, '.cursorrules'), buildCursorRules());
  files.cursorRules = '.cursorrules';

  writeFileIfContent(
    path.join(projectPath, '.opencode', 'config.md'),
    buildOpenCodeConfig({ projectName })
  );
  files.opencodeConfig = '.opencode/config.md';

  const scaffold = createScaffold({
    projectPath,
    projectName,
    safeName,
    templateId,
    projectType,
    blueprint: useBlueprint,
    prototypeHtml: fullPrototype,
  });
  files.scaffold = scaffold.paths;
  files.manifest = 'cauldron.project.json';

  let bootstrapResult = null;
  if (bootstrap && scaffold.packageManager) {
    bootstrapResult = await bootstrapScaffold(projectPath, scaffold.id);
  }

  writeFileIfContent(
    path.join(projectPath, 'launch-checklist.md'),
    buildLaunchChecklist({
      projectName,
      scaffold,
      verification,
      designReference,
      createdAt: new Date().toISOString(),
      projectPath,
    })
  );
  files.launchChecklist = 'launch-checklist.md';

  const manifest = {
    schemaVersion: 1,
    projectName: safeName,
    displayName: projectName,
    createdAt: new Date().toISOString(),
    source: 'cauldron-os',
    cauldronVersion,
    projectType,
    templateId,
    designReference: designReference || 'none',
    sessionId: sessionId || null,
    files,
    copiedWorkspaceFiles: buildFilesList,
    scaffold,
    bootstrap: bootstrapResult,
    verification,
    exports: {
      designPackage: includeDesignPackage
        ? {
            markdown: 'docs/design.md',
            html: 'docs/design.html',
          }
        : null,
    },
    agent: {
      mode: command ? 'launched' : 'handoff-only',
      requestedCli: agentId === 'handoff' ? null : agentId,
      command,
      scope,
    },
  };

  writeFileIfContent(
    path.join(projectPath, 'cauldron.project.json'),
    JSON.stringify(manifest, null, 2) + '\n'
  );

  return {
    projectPath,
    manifestPath: path.join(projectPath, 'cauldron.project.json'),
    files,
    filesCopied: buildFilesList.length,
    blueprint: useBlueprint || '',
    manifest,
    bootstrap: bootstrapResult,
  };
}

