function getAgentScope(agentId = 'handoff') {
  return AGENT_SCOPES[agentId] || AGENT_SCOPES.handoff;
}

function buildReadme({ projectName, agentId, templateId, projectType, agentScope = null }) {
  const scaffoldLabel = templateId || 'html-alpine';
  const scope = agentScope || getAgentScope(agentId);
  return `# ${projectName}\n\nGenerated by Cauldron OS as a build-agent handoff package.\n\n## Included\n\n- \`blueprint.md\` — product and implementation specification\n- \`prototype.html\` — standalone HTML prototype when available\n- \`design-system.md\` — selected design reference content\n- \`launch-checklist.md\` — human runbook and verification summary\n- \`cauldron.project.json\` — machine-readable handoff manifest\n- \`agent-prompt.md\` — prompt for your build agent CLI\n- \`.opencode/config.md\` — OpenCode-oriented manual instructions\n- Scaffold starter files for \`${scaffoldLabel}\`\n\n## Run The Scaffold\n\n- Static/HTML templates: open \`index.html\` in a browser.\n- Package templates: run \`npm install\`, then \`npm run dev\`.\n\n## Build With Your Agent\n\n1. Open this folder in your preferred coding agent.\n2. Read \`agent-prompt.md\` first.\n3. Use \`blueprint.md\`, \`prototype.html\`, and \`design-system.md\` as the source of truth.\n4. Check \`launch-checklist.md\` for commands, verification results, and remaining human steps.\n5. Build a runnable ${scaffoldLabel || projectType || 'project'} scaffold.\n6. Keep implementation notes and any remaining setup steps in this README.\n\nRequested agent: ${agentId || 'handoff-only'}\n\n## Agent Scope\n\n${scope.label}\n\n${scope.focus}\n`;
}

function buildAgentPrompt({
  projectName,
  templateId,
  projectType,
  agentId = 'handoff',
  agentScope = null,
  orchestration = null,
}) {
  const scope = agentScope || getAgentScope(agentId);
  const siblingNotes =
    Array.isArray(orchestration?.agents) && orchestration.agents.length > 1
      ? `\n\n## Multi-Agent Context\nYou are one agent in a coordinated build handoff. Other selected agents: ${orchestration.agents.map((agent) => agent.name || agent.id).join(', ')}.\nStay inside your scope, but leave clear notes for the rest of the build team.`
      : '';

  return `You are building ${projectName} from a Cauldron OS handoff package.\n\n## Your Scope\n${scope.label}\n\n${scope.focus}\n\nPrimary files to inspect first:\n${scope.files.map((file) => `- ${file}`).join('\n')}\n\nRead these files before editing:\n\n1. blueprint.md\n2. prototype.html, if present\n3. design-system.md\n4. cauldron.project.json\n\nBuild the most useful runnable ${templateId || projectType || 'project'} version from the spec. Preserve the visual direction from the prototype and design system. Add realistic local demo data where needed. Do not require real secrets; create .env.example for credentials. Finish by updating README.md with run instructions and remaining caveats.${siblingNotes}`;
}

